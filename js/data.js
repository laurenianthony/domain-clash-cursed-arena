const defineCard = (characterId, id, name, type, cost, effects, desc, color) => ({
  id,
  characterId,
  theme: characterId,
  name,
  type,
  cost,
  ...effects,
  desc,
  color,
});

const makeCharacter = (id, name, title, hp, maxCe, passive, passiveText, accent, cardPool, starterDeck) => ({
  id,
  name,
  title,
  hp,
  maxHp: hp,
  maxCe,
  portrait: `./assets/characters/${id}.jpg`,
  passive,
  passiveText,
  accent,
  cardPool: Object.freeze(cardPool),
  starterDeck: Object.freeze(starterDeck),
});

